import { val } from './units.js';

export function resolveSpacecraft(sc, data) {
  const byId = (list, id) => list.find((x) => x.id === id);
  return {
    parts: sc.components.map((id) => byId(data.components.components, id)).filter(Boolean),
    instruments: sc.instruments.map((id) => byId(data.components.instruments, id)).filter(Boolean),
    allInstruments: data.components.instruments,
    launcher: byId(data.components.launchers, sc.launcherId) || null,
    orbit: byId(data.orbits.orbits, sc.orbitId) || null,
  };
}

const all = (r) => [...r.parts, ...r.instruments];
const sum = (items, key) => items.reduce((s, it) => s + (val(it[key]) || 0), 0);

export const dryMassKg = (r) => sum(all(r), 'mass_kg');
export const propellantKg = (r) => sum(r.parts, 'propellant_kg');
export const wetMassKg = (r) => dryMassKg(r) + propellantKg(r);
export const powerGeneratedW = (r) => sum(r.parts, 'power_generated_w');   // W, sunlit output
export const powerConsumedW = (r) => sum(all(r), 'power_w');               // W
export const batteryCapacityWh = (r) => sum(r.parts, 'capacity_wh');       // Wh
export const costUsdM = (r) => sum(all(r), 'cost_usd_m') + (r.launcher ? val(r.launcher.cost_usd_m) : 0);
export const dataRateKbps = (r) => sum(r.instruments, 'data_rate_kbps');   // generated by instruments
export const downlinkRateKbps = (r) => sum(r.parts, 'downlink_kbps');

export const massMarginKg = (r) => (r.launcher ? val(r.launcher.capacity_kg) - wetMassKg(r) : 0);
export const massMarginFrac = (r) => (r.launcher ? massMarginKg(r) / val(r.launcher.capacity_kg) : 0);

export const powerMarginW = (r) => powerGeneratedW(r) - powerConsumedW(r);
export const powerMarginFrac = (r) => (powerConsumedW(r) > 0 ? powerMarginW(r) / powerConsumedW(r) : 0);

export function eclipseEnergyWh(r) {
  if (!r.orbit) return 0;
  const eclipseS = val(r.orbit.eclipse_fraction) * val(r.orbit.period_s);
  return (powerConsumedW(r) * eclipseS) / 3600;
}
export const batteryMarginWh = (r) => batteryCapacityWh(r) - eclipseEnergyWh(r);
export const batteryMarginFrac = (r) => {
  const need = eclipseEnergyWh(r);
  return need > 0 ? batteryMarginWh(r) / need : 0;
};

export const scienceFrac = (r) => {
  const best = sum(r.allInstruments || [], 'science_value');
  return best > 0 ? sum(r.instruments, 'science_value') / best : 0;
};

// Thermal: every watt consumed ends up as heat. Margin = (heat the bus can reject - heat produced) / heat it can reject.
// Returns -1 when no bus gives a rejection figure (nothing can shed heat).
export function thermalMarginFrac(r) {
  const rejectW = sum(r.parts, 'thermal_rejection_w');
  if (rejectW <= 0) return -1;
  return (rejectW - powerConsumedW(r)) / rejectW;
}